"""Noise-level schedule, calibration bins, and guided window (paper: Tab. "activation", upper part).

Degree constraints of family r are active only at guided steps whose noise bin is valid for r
(nu~_{r,b} = 1). Whether degree guidance can activate at all is therefore a property of the
sampler's sigma schedule, the bin edges, and the guided window W = {t : sigma_t >= sigma_lo}.
This script computes it exactly from the diffusers scheduler (no download needed):
  * sigma_t of every sampling step for the configured steps and shift,
  * the B equal-width bins in sigma and the steps that fall into each,
  * for candidate windows sigma_lo, the number of guided steps available to a family whose
    validity starts at bin b0 (validity is contiguous up to the final bin, App. A.3).

Usage:  python -I activation_schedule.py [--steps 28] [--shift 3.0] [--bins 4]
                                         [--windows 0.75 0.5 0.25 0.0] [--out DIR]
Writes schedule_rows.tex (\\scheduleBinRows, \\scheduleWindowRows) and schedule.json.
"""
import argparse
import json
import os

import numpy as np
from diffusers import FlowMatchEulerDiscreteScheduler


def schedule(steps, shift):
    s = FlowMatchEulerDiscreteScheduler(num_train_timesteps=1000, shift=shift)
    s.set_timesteps(steps)
    return s.sigmas.numpy()[:-1]          # sigma at which each of the `steps` velocities is evaluated


def bin_of(sig, n_bins):
    """Bins b = 1 (noisiest) ... B (cleanest), equal width in sigma on [0, 1]."""
    edges = np.linspace(1.0, 0.0, n_bins + 1)          # 1.0, 0.75, 0.5, 0.25, 0.0 for B = 4
    b = np.searchsorted(-edges[1:-1], -sig, side="right") + 1
    return b, edges


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--steps", type=int, default=28)
    ap.add_argument("--shift", type=float, default=3.0)
    ap.add_argument("--bins", type=int, default=4)
    ap.add_argument("--windows", type=float, nargs="+", default=[0.75, 0.5, 0.25, 0.0])
    ap.add_argument("--out", default=os.path.dirname(os.path.abspath(__file__)))
    a = ap.parse_args()

    sig = schedule(a.steps, a.shift)
    b, edges = bin_of(sig, a.bins)
    res = {"steps": a.steps, "shift": a.shift, "bins": a.bins,
           "sigma": [round(float(x), 4) for x in sig], "bin": [int(x) for x in b], "windows": {}}

    bin_rows = []
    for k in range(1, a.bins + 1):
        idx = np.where(b == k)[0]
        hi, lo = edges[k - 1], edges[k]
        rng = f"{idx[0] + 1}--{idx[-1] + 1}" if len(idx) else "--"
        smax = f"{sig[idx].max():.2f}" if len(idx) else "--"
        smin = f"{sig[idx].min():.2f}" if len(idx) else "--"
        lb = "[" if k == a.bins else "["
        rb = "]" if k == 1 else ")"
        bin_rows.append(f"$b={k}$ & ${lb}{lo:.2f},{hi:.2f}{rb}$ & {rng} & {len(idx)} & {smax}--{smin}\\\\")

    win_rows = []
    for lo in a.windows:
        g = sig >= lo
        per_b0 = [int(np.sum(g & (b >= b0))) for b0 in range(1, a.bins + 1)]
        res["windows"][str(lo)] = {"guided_steps": int(g.sum()), "available_by_first_valid_bin": per_b0}
        win_rows.append(f"$\\sigma_t\\ge{lo:.2f}$ & {int(g.sum())} & " + " & ".join(str(x) for x in per_b0) + "\\\\")

    with open(os.path.join(a.out, "schedule.json"), "w") as f:
        json.dump(res, f, indent=2)
    with open(os.path.join(a.out, "schedule_rows.tex"), "w") as f:
        f.write(f"% Generated by activation_schedule.py (steps={a.steps}, shift={a.shift}, B={a.bins}); do not edit.\n")
        f.write("\\providecommand{\\scheduleBinRows}{%\n" + "\n".join(bin_rows) + "\n}\n")
        f.write("\\providecommand{\\scheduleWindowRows}{%\n" + "\n".join(win_rows) + "\n}\n")
    print(json.dumps(res["windows"], indent=1))
    print("\n".join(bin_rows))


if __name__ == "__main__":
    main()
