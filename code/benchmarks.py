"""Standard benchmarks for Table 38: GenEval and T2I-CompBench++.

Images are generated by run_experiment.py like any other run. This module does the two conversions around
that run, so the notebook only ever names a benchmark:

  prompts BENCH [--n N] --out FILE    the benchmark's prompts as a JSON list for --prompts-file
                                      (--n takes a fixed random subset, for a pilot of the pipeline only)
  seeds BENCH                         the seeds to generate: one per image the benchmark asks for
  export BENCH --run DIR --arm ARM --out DIR
                                      the arm's finished images in the layout the official scorer reads

Export works out what was run from the run folder, so a pilot and a full run use the same command. A prompt
is exported only when every seed of the run finished for it; partial prompts are counted, never scored.

The official prompt files are read from clones next to this repository (the notebook makes them), or from
--sources. Layouts follow each benchmark's README and evaluation scripts:

  GenEval          <out>/00000/metadata.jsonl   the prompt's line of evaluation_metadata.jsonl, unchanged
                   <out>/00000/samples/0000.png image k is seed k
  T2I-CompBench++  <out>/samples/<prompt>_000000.png   one running number over the whole prompt file

  python -I code/benchmarks.py export geneval --run outputs/bench_geneval --arm stage1_sar --out outputs/x
"""
from __future__ import annotations

import argparse
import json
import random
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, List, Tuple

DEFAULT_SOURCES = Path(__file__).resolve().parents[2]


@dataclass(frozen=True)
class Benchmark:
    name: str
    images: int                                         # images per prompt the official protocol asks for
    source: str                                         # prompt file, relative to the sources folder
    read: Callable[[Path], List[Tuple[str, str]]]       # file -> [(prompt, the prompt's own record)]
    write: Callable[[Path, int, str, List[Path], int], None]   # (out, index, record, images, images per prompt)

    def prompts(self, sources=DEFAULT_SOURCES) -> List[Tuple[str, str]]:
        return self.read(Path(sources) / self.source)


def _read_geneval(path):
    lines = [line for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    return [(json.loads(line)["prompt"], line) for line in lines]


def _read_t2i(path):
    prompts = [line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    bad = [p for p in prompts if "_" in p or "/" in p]
    if bad:
        raise ValueError(f"the scorer reads the prompt back from <prompt>_<n>.png, so '_' and '/' are not allowed: {bad[:3]}")
    return [(p, p) for p in prompts]


def _write_geneval(out, index, record, images, per_prompt):
    folder = out / f"{index:05d}"
    (folder / "samples").mkdir(parents=True, exist_ok=True)
    (folder / "metadata.jsonl").write_text(record + "\n", encoding="utf-8")
    for k, image in enumerate(images):
        shutil.copyfile(image, folder / "samples" / f"{k:04d}.png")


def _write_t2i(out, index, prompt, images, per_prompt):
    samples = out / "samples"
    samples.mkdir(parents=True, exist_ok=True)
    for k, image in enumerate(images):
        shutil.copyfile(image, samples / f"{prompt}_{index * per_prompt + k:06d}.png")


T2I_CATEGORIES = ("color", "texture", "shape", "spatial")
BENCHMARKS = {"geneval": Benchmark("geneval", 4, "geneval/prompts/evaluation_metadata.jsonl", _read_geneval, _write_geneval)}
BENCHMARKS.update({c: Benchmark(c, 10, f"T2I-CompBench/examples/dataset/{c}_val.txt", _read_t2i, _write_t2i)
                   for c in T2I_CATEGORIES})


def subset(prompts, n=None, seed=0):
    """n items drawn at random, the same every time, kept in file order. For a pilot only."""
    if n is None or n >= len(prompts):
        return list(prompts)
    keep = set(random.Random(f"bench|{seed}").sample(range(len(prompts)), n))
    return [p for i, p in enumerate(prompts) if i in keep]


def finished_images(run, arm):
    """{prompt: {seed: image path}} for every finished image of one arm of a run."""
    found = {}
    for meta_path in Path(run, arm).glob("*/meta.json"):
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        image = meta_path.parent / "image.png"
        if "failed" not in meta and image.exists():
            found.setdefault(meta["prompt"], {})[meta["seed"]] = image
    return found


def export(bench: Benchmark, run, arm, out, sources=DEFAULT_SOURCES):
    """Writes the arm's complete prompts in the official layout. Returns counts of exported prompts, prompts
    with a seed still missing, and benchmark prompts the run does not contain."""
    found = finished_images(run, arm)
    seeds = sorted({s for by_seed in found.values() for s in by_seed})
    counts = {"exported": 0, "incomplete": 0, "not_run": 0, "seeds": len(seeds)}
    for index, (prompt, record) in enumerate(bench.prompts(sources)):
        by_seed = found.get(prompt)
        if by_seed is None:
            counts["not_run"] += 1
        elif any(s not in by_seed for s in seeds):
            counts["incomplete"] += 1
        else:
            bench.write(Path(out), index, record, [by_seed[s] for s in seeds], bench.images)
            counts["exported"] += 1
    return counts


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("command", choices=["prompts", "seeds", "export"])
    ap.add_argument("benchmark", choices=sorted(BENCHMARKS))
    ap.add_argument("--sources", default=str(DEFAULT_SOURCES), help="folder holding the geneval and T2I-CompBench clones")
    ap.add_argument("--out")
    ap.add_argument("--n", type=int, default=None, help="prompts: a fixed random subset of n, for a pilot only")
    ap.add_argument("--run", help="export: the run folder")
    ap.add_argument("--arm", help="export: the arm to export")
    args = ap.parse_args()
    bench = BENCHMARKS[args.benchmark]

    if args.command == "seeds":
        print(",".join(str(k) for k in range(bench.images)))
    elif args.command == "prompts":
        if not args.out:
            ap.error("prompts needs --out")
        prompts = subset([p for p, _ in bench.prompts(args.sources)], args.n)
        Path(args.out).write_text(json.dumps(prompts, indent=1), encoding="utf-8")
        print(f"{bench.name}: {len(prompts)} prompts -> {args.out}")
    else:
        if not (args.run and args.arm and args.out):
            ap.error("export needs --run, --arm and --out")
        c = export(bench, args.run, args.arm, args.out, args.sources)
        print(f"{bench.name} {args.arm}: exported {c['exported']} prompts with {c['seeds']} images each to {args.out};"
              f" {c['incomplete']} incomplete, {c['not_run']} not in this run")
        if c["seeds"] != bench.images:
            print(f"  {c['seeds']} images per prompt where the benchmark asks for {bench.images}: a pilot, not a score")


if __name__ == "__main__":
    main()
