"""Single source of truth for every setting reported in the paper.

configs/fuzzydiff_sd3.yaml holds each setting once, with its LaTeX value and a status:
  verified  - checked (diffusers source, computation, or the loaded checkpoint);
  proposed  - a default that must be replaced by the value of the actual run.
The experiment code should load the same YAML (see `load()` below), so the paper and the
runs cannot disagree. This script writes config.tex from the YAML; proposed values are
wrapped in \\verify{} (orange in the annotated build). config.tex then inputs
code/backbone_config.tex (written by verify_checkpoint.py from the loaded checkpoint), which
overrides the backbone entries with the loaded values.

Usage:
  python -I code/make_config.py            # YAML -> config.tex
  python -I code/make_config.py --status   # list settings that are still proposed
  python -I code/make_config.py --import-tex config.tex   # one-time: config.tex -> YAML
"""
import argparse
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
YAML_PATH = os.path.join(ROOT, "configs", "fuzzydiff_sd3.yaml")
TEX_PATH = os.path.join(ROOT, "config.tex")


def load(path=YAML_PATH):
    """Return {macro_name: value_string} for use by experiment code."""
    with open(path) as f:
        data = yaml.safe_load(f)
    return {e["name"]: e["value"] for g in data["groups"] for e in g["settings"]}


def _braced(s, i):
    """Return (content, end_index) of the balanced {...} starting at s[i] == '{'."""
    assert s[i] == "{"
    depth = 0
    for j in range(i, len(s)):
        if s[j] == "{":
            depth += 1
        elif s[j] == "}":
            depth -= 1
            if depth == 0:
                return s[i + 1:j], j + 1
    raise ValueError("unbalanced braces")


def import_tex(path):
    groups, cur = [], None
    for line in open(path):
        m = re.match(r"^% --- (.*?) ---", line)
        if m:
            cur = {"group": m.group(1), "settings": []}
            groups.append(cur)
            continue
        m = re.match(r"^\\newcommand\{\\(cfg\w+)\}", line)
        if not m:
            continue
        val, end = _braced(line, m.end())
        note = line[end:].strip().lstrip("%").strip()
        status = "verified"
        if val.startswith("\\verify{"):
            inner, e2 = _braced(val, len("\\verify"))
            if e2 == len(val):
                val, status = inner, "proposed"
        if cur is None:
            cur = {"group": "misc", "settings": []}
            groups.append(cur)
        entry = {"name": m.group(1), "value": val, "status": status}
        if note:
            entry["note"] = note
        cur["settings"].append(entry)
    return {"groups": groups}


def write_tex(data, path=TEX_PATH):
    n_all = sum(len(g["settings"]) for g in data["groups"])
    n_prop = sum(e["status"] == "proposed" for g in data["groups"] for e in g["settings"])
    out = [
        "%% ===================================================================",
        "%% config.tex -- GENERATED by code/make_config.py from configs/fuzzydiff_sd3.yaml.",
        "%% Do not edit; edit the YAML (which the experiment code also reads) and rerun.",
        "%% Values in \\verify{} have status 'proposed' and must be replaced by run values.",
        "%% ===================================================================",
    ]
    for g in data["groups"]:
        out.append(f"% --- {g['group']} ---")
        for e in g["settings"]:
            v = e["value"]
            v = f"\\verify{{{v}}}" if e["status"] == "proposed" else v
            note = f"  % {e['note']}" if e.get("note") else ""
            out.append(f"\\newcommand{{\\{e['name']}}}{{{v}}}{note}")
    out.append("% --- bookkeeping ---")
    out.append(f"\\newcommand{{\\cfgCountAll}}{{{n_all}}}")
    out.append(f"\\newcommand{{\\cfgCountProposed}}{{{n_prop}}}")
    out.append("% values read from the loaded checkpoint (verify_checkpoint.py) override the above")
    out.append("\\IfFileExists{code/backbone_config.tex}{\\input{code/backbone_config.tex}}{}")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    return n_all, n_prop


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--import-tex")
    ap.add_argument("--status", action="store_true")
    args = ap.parse_args()
    if args.import_tex:
        data = import_tex(args.import_tex)
        os.makedirs(os.path.dirname(YAML_PATH), exist_ok=True)
        with open(YAML_PATH, "w") as f:
            f.write("# FuzzyDiff settings: single source for the paper (config.tex) and the experiment code.\n")
            f.write("# status: verified | proposed. Replace every 'proposed' value by the value of the run.\n")
            yaml.safe_dump(data, f, sort_keys=False, allow_unicode=True, width=120)
        print(f"wrote {YAML_PATH}")
        return
    with open(YAML_PATH) as f:
        data = yaml.safe_load(f)
    if args.status:
        for g in data["groups"]:
            for e in g["settings"]:
                if e["status"] == "proposed":
                    print(f"{g['group']:<45} {e['name']:<18} {e['value']}")
        return
    n_all, n_prop = write_tex(data)
    print(f"wrote {TEX_PATH}: {n_all} settings, {n_prop} still proposed")


if __name__ == "__main__":
    sys.exit(main())
