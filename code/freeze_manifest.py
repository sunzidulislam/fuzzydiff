"""Freeze which predicate families are degree-guided, BEFORE any test image is generated.

Inputs (non-test data only; reporting.decide_support raises LeakageError on test records):
  --validity  validity.json    {family: {"final_bin_valid": bool}}                 (G_cal)
  --single    single.json      {family: {"dir_lb": float, "slope_lb": float}}       (G_int)
  --system    system.jsonl     guidance logs of full multi-constraint runs           (G_sys)
  --pairs     pairs.jsonl      paired transfer measurements on G_sys images          (G_sys)
  --config    configs/fuzzydiff_sd3.yaml (n_act, activation share, pass thresholds)

Writes support_manifest.json (statuses, failed criteria, input file hashes, SHA-256 of the
manifest itself) and support_rows.tex, which the paper reads for the "Status" column of the
predicate-status table and prints the manifest hash. Test-time scripts load the manifest and
must not modify it; reporting on test data never changes a status.

Usage: python -I freeze_manifest.py --validity v.json --single s.json --system sys.jsonl --pairs p.jsonl
"""
import argparse
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from reporting import decide_support, read_jsonl  # noqa: E402

UNSUPPORTED = ["counts", "physical quantities", "motion", "depth", "containment", "manner adverbs",
               "unlisted hedges"]
SHORT = {"degree-guided": "degree", "presence/binding only": "pres./bind.", "unsupported": "unsupp."}


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def _num(s):
    return float(str(s).strip("$\\verify{}"))


def freeze(validity, single, system, pairs, cfg, out_dir, inputs=None):
    status = decide_support(validity, single, system, pairs, n_act=int(_num(cfg["cfgNact"])),
                            act_share=_num(cfg["cfgActShare"]), dir_min=_num(cfg["cfgDirAcc"]),
                            slope_min=_num(cfg["cfgTransfer"]), unsupported=UNSUPPORTED)
    manifest = {"status": status, "inputs": inputs or {},
                "rule": "degree-guided iff valid at final bin, single-family gradient validity, "
                        "activation rule, and full-system transfer all pass (non-test data only)"}
    body = json.dumps(manifest, indent=2, sort_keys=True)
    digest = hashlib.sha256(body.encode()).hexdigest()
    manifest["sha256"] = digest
    with open(os.path.join(out_dir, "support_manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
    with open(os.path.join(out_dir, "support_rows.tex"), "w") as f:
        f.write("% Generated by freeze_manifest.py; do not edit.\n")
        f.write(f"\\renewcommand{{\\manifestHash}}{{\\texttt{{{digest[:12]}}}}}\n")
        for fam, st in status.items():
            f.write(f"\\expandafter\\def\\csname fdstatus@{fam}\\endcsname{{{SHORT[st['status']]}}}\n")
    return manifest


def main():
    ap = argparse.ArgumentParser()
    for k in ("validity", "single", "system", "pairs"):
        ap.add_argument(f"--{k}", required=True)
    ap.add_argument("--out", default=os.path.dirname(os.path.abspath(__file__)))
    a = ap.parse_args()
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from make_config import load
    m = freeze(json.load(open(a.validity)), json.load(open(a.single)), read_jsonl(a.system),
               read_jsonl(a.pairs), load(), a.out,
               inputs={k: sha256(getattr(a, k)) for k in ("validity", "single", "system", "pairs")})
    print(json.dumps({k: v["status"] for k, v in m["status"].items()}, indent=1))
    print("manifest sha256:", m["sha256"])


if __name__ == "__main__":
    main()
