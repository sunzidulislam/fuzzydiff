"""Write processor_check_rows.tex (paper Tab. "processor_check") from
processor_check.json (random-weight unit tests, test_processor.py), arch_check.json
(random weights at SD3-Medium layer dimensions, arch_check.py) and, if present,
checkpoint_check.json (actual checkpoint, verify_checkpoint.py)."""
import json
import os

ROWS = [  # (label, key)
    ("Identity, output", "identity_out"),
    ("Identity, input gradient", "identity_grad"),
    ("SAR with $r{=}1$, output", "sar_r1_out"),
    ("Readout vs.\\ materialized, values", "readout_val"),
    ("Phrase text-share vs.\\ materialized", "share_val"),
    ("Absolute text mass vs.\\ materialized", "mass_val"),
    ("Readout vs.\\ materialized, gradient", "readout_grad"),
    ("SAR bias vs.\\ renormalized reweighting", "sar_equiv"),
    ("SAR: uncond.\\ branch unchanged", "sar_uncond"),
]


def _fmt(v):
    if isinstance(v, bool):
        return "pass" if v else "FAIL"
    if isinstance(v, (list, tuple)) and len(v) == 2:
        return f"${v[0]:.1e}$ (${v[1]:.1e}$)"
    return str(v)


def write_rows(out_dir):
    with open(os.path.join(out_dir, "processor_check.json")) as f:
        rnd = json.load(f)
    ck_path = os.path.join(out_dir, "checkpoint_check.json")
    ck = json.load(open(ck_path)) if os.path.exists(ck_path) else None
    ck_qk = None if ck is None else ("qk-norm" if ck.get("qk_norm") else "no qk-norm")
    ar_path = os.path.join(out_dir, "arch_check.json")
    ar = json.load(open(ar_path)) if os.path.exists(ar_path) else None

    def arch(key, tag):  # SD3-Medium has no QK-norm, so the arch check fills the no-QK-norm rows only
        if ar is None:
            return "\\tbd"
        return _fmt(ar[key]) if (tag == "no qk-norm" and key in ar) else "--"
    lines = []
    for tag in ("no qk-norm", "qk-norm"):
        sfx = " (QK-norm)" if tag == "qk-norm" else ""
        for label, key in ROWS:
            r = _fmt(rnd[f"{key}_{tag}"])
            if ck is None:
                c = "\\tbd"
            elif tag == ck_qk and key in ck:
                c = _fmt(ck[key])
            else:
                c = "--"
            lines.append(f"{label}{sfx} & {r} & {arch(key, tag)} & {c}\\\\")
    lines.append("Finite-difference gradcheck of readout & " + _fmt(rnd["gradcheck_readout"]) + " & -- & --\\\\")
    c = "\\tbd" if ck is None else _fmt(ck.get("fd_grad", "--"))
    lines.append("Finite-difference directional derivative, full model & " + _fmt(rnd["fd_grad_no qk-norm"]) + " & "
                 + arch("fd_grad", "no qk-norm") + " & " + c + "\\\\")
    for label, key in [("T5 token index $j\\mapsto N_I{+}77{+}j$", "token_index"),
                       ("Pipeline image, modulation off (max.\\ pixel diff.)", "image_identity")]:
        c = "\\tbd" if ck is None else _fmt(ck.get(key, "--"))
        lines.append(f"{label} & n/a & n/a & {c}\\\\")
    with open(os.path.join(out_dir, "processor_check_rows.tex"), "w") as f:
        f.write("% Generated by table_rows.py; do not edit.\n")
        f.write("\\providecommand{\\processorRows}{%\n" + "\n".join(lines) + "\n}\n")
