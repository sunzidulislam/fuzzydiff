"""Write LaTeX rows for the result tables from run outputs (reporting.py does the statistics).

Each table in the paper uses \\ifdefined\\<name>Rows ... \\else <TBD rows> \\fi, so it shows TBD
until this script has produced results_rows.tex from real runs.

Inputs (any subset; missing inputs leave the corresponding table at TBD):
  --sys-logs   G_sys guidance logs (JSONL)         -> \\activationRows (G_sys column)
  --test-logs  test guidance logs (JSONL)          -> \\activationRows (test, confirmatory), \\tierRows
  --sys-pairs / --test-pairs  paired transfer data -> \\transferRows
  --shift      calibration-shift records (JSONL)   -> \\shiftRows
  --intervals  interval-ablation judgments (JSONL) -> \\intervalRows
Usage: python -I make_tables.py --sys-logs s.jsonl --test-logs t.jsonl ... [--out DIR]
"""
import argparse
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from reporting import (activation_rows, interval_rows, read_jsonl, shift_rows, tier_rows,  # noqa: E402
                       transfer_rows)

FAMILY_LABEL = {"F1": "F1 Visibility", "F2a": "F2a Photometric attribute", "F2b": "F2b Open-vocab.\\ attribute",
                "F4": "F4 Attribute blending", "F6": "F6 Color mixture / hedged color", "F8": "F8 Relative size",
                "Binding": "Binding (attribute--object)"}
VARIANT_LABEL = {"unguided": "Unguided backbone", "interval": "Two-sided interval (ours)",
                 "point": "(a) Point target at center", "onesided": "(b) One-sided (more is better)",
                 "hard": "(c) Hard interval", "heuristic": "(d) Heuristic intervals"}


def f(x, d=2):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return f"{x:.{d}f}" if isinstance(x, float) else str(x)


def pct(x):
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.0f}"


def main():
    ap = argparse.ArgumentParser()
    for k in ("sys-logs", "test-logs", "sys-pairs", "test-pairs", "shift", "intervals"):
        ap.add_argument(f"--{k}")
    ap.add_argument("--n-act", type=int, default=3)
    ap.add_argument("--out", default=os.path.dirname(os.path.abspath(__file__)))
    a = ap.parse_args()
    out = ["% Generated by make_tables.py from run outputs; do not edit."]

    if a.sys_logs:
        sysa = activation_rows(read_jsonl(a.sys_logs), a.n_act)
        tsta = activation_rows(read_jsonl(a.test_logs), a.n_act) if a.test_logs else {}
        rows = []
        for fam, r in sysa.items():
            t = tsta.get(fam, {})
            rows.append(f"{FAMILY_LABEL.get(fam, fam)} & {f(r['b0'])} & {f(r['active_median'], 1)} ({f(t.get('active_median'), 1)}) & "
                        f"{pct(r['share_ge_nact'])} ({pct(t.get('share_ge_nact'))}) & {r['block']} & {pct(r['accepted_share'])} & "
                        f"{f(r['dL3_per_accepted'], 3)} & {f(r['mu_unguided'])}$\\to${f(r['mu_guided'])}\\\\")
        out.append("\\def\\activationRows{%\n" + "\n".join(rows) + "\n}")

    if a.test_logs:
        tr = tier_rows(read_jsonl(a.test_logs))
        rows = [f"Tier {m} & {pct(tr[m]['viol_unguided'])}$\\to${pct(tr[m]['viol_guided'])} & {pct(tr[m]['conflict_share'])} & "
                f"{f(tr[m]['removed_mean'])} & {pct(tr[m]['finite_step_failures'])}\\\\" for m in (1, 2, 3)]
        reasons = ", ".join(f"{k} {v}" for k, v in sorted(tr["rejections"]["reasons"].items()))
        rows.append(f"\\multicolumn{{5}}{{@{{}}l}}{{Rejected candidates: {pct(tr['rejections']['rate'])}\\% ({reasons})}}\\\\")
        out.append("\\def\\tierRows{%\n" + "\n".join(rows) + "\n}")

    if a.sys_pairs:
        ts = transfer_rows(read_jsonl(a.sys_pairs))
        tt = transfer_rows(read_jsonl(a.test_pairs)) if a.test_pairs else {}
        rows = []
        for fam, r in ts.items():
            t = tt.get(fam, {})
            sb = r["slope_by_active"]
            rows.append(f"{FAMILY_LABEL.get(fam, fam)} & {r['n']} & {pct(r['dir_acc'])} ({pct(t.get('dir_acc'))}) & "
                        f"{f(r['slope'])} [{f(r['slope_ci'][0])}, {f(r['slope_ci'][1])}] ({f(t.get('slope'))}) & "
                        f"{f(sb['1'])} / {f(sb['2'])} / {f(sb['>=3'])} & {pct(r['exploitation'])} ({pct(t.get('exploitation'))})\\\\")
        out.append("\\def\\transferRows{%\n" + "\n".join(rows) + "\n}")

    if a.shift:
        sh = shift_rows(read_jsonl(a.shift))
        rows = [f"{FAMILY_LABEL.get(fam, fam)} & {src} & {r['n']} & {f(r['spearman'])} & {f(r['ece'], 3)} & {pct(r['out_of_domain'])}\\\\"
                for (fam, src), r in sh.items()]
        out.append("\\def\\shiftRows{%\n" + "\n".join(rows) + "\n}")

    if a.intervals:
        iv = interval_rows(read_jsonl(a.intervals))
        rows = [f"{VARIANT_LABEL.get(v, v)} & {pct(r['pair'])} & {pct(r['acc'])} & {pct(r['over'])} & {pct(r['under'])} & "
                f"{pct(r['ofa'])} & {f(r['change_on_ok'])} & {f(r['nfe'], 0)} / {f(r['seconds'], 1)}\\\\" for v, r in iv.items()]
        out.append("\\def\\intervalRows{%\n" + "\n".join(rows) + "\n}")

    path = os.path.join(a.out, "results_rows.tex")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {path} ({len(out) - 1} tables)")


if __name__ == "__main__":
    main()
